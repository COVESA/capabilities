#!/usr/bin/env python3
"""Export the capability/VSS/VDM graph for docs and review.

Writes, deterministically:

  docs/graph/model.json               - the full graph, sorted
  docs/graph/<capability>.mmd         - a Mermaid diagram of one capability, 2 hops out

Usage::

    python scripts/export_graph.py            # write
    python scripts/export_graph.py --check    # fail if the export is stale
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from capability_framework.semantics import VssCatalog, load_catalog  # noqa: E402
from capability_framework.semantics.graph import build_graph  # noqa: E402
from capability_framework.semantics.vdm import VdmSchema  # noqa: E402


def load_graph():
    lock = json.loads((ROOT / "third_party" / "standards.lock.json").read_text(encoding="utf-8"))
    return build_graph(
        catalog=load_catalog(ROOT / "catalog" / "capabilities"),
        vss=VssCatalog.from_json(ROOT / "third_party" / "generated" / "vss.json"),
        vdm=VdmSchema.from_sdl_file(ROOT / "third_party" / "generated" / "vdm.graphql"),
        contracts_dir=ROOT / "contracts",
        vss_version=lock["standards"]["vss"]["version_label"],
    )


def mermaid(graph, root: str) -> str:
    sub = graph.subgraph(root, depth=2)
    lines = ["%% Generated by scripts/export_graph.py - do not edit.", "flowchart LR"]
    for node in sub.nodes:
        shape_open, shape_close = {
            "Capability": ("[", "]"),
            "Operation": ("(", ")"),
            "SouthboundPort": ("[/", "/]"),
            "Contract": ("[[", "]]"),
            "Schema": ("{{", "}}"),
            "VssSignal": ("[", "]"),
            "VdmField": ("[", "]"),
            "VdmType": ("[", "]"),
            "Requirement": ("[", "]"),
            "TestCase": ("[", "]"),
        }.get(node.type, ("[", "]"))
        label = node.label.replace('"', "'")
        lines.append(f'    {_ident(node.id)}{shape_open}"{label}"{shape_close}')
    for edge in sub.edges:
        lines.append(f"    {_ident(edge.source)} -->|{edge.relation}| {_ident(edge.target)}")
    for node in sub.nodes:
        lines.append(f"    class {_ident(node.id)} {node.layer};")
    lines.append("    classDef capability fill:#dbeafe,stroke:#1d4ed8,color:#0b1b33;")
    lines.append("    classDef contract fill:#ede9fe,stroke:#6d28d9,color:#1b0b33;")
    lines.append("    classDef vss fill:#dcfce7,stroke:#15803d,color:#06230f;")
    lines.append("    classDef vdm fill:#fef3c7,stroke:#b45309,color:#241503;")
    lines.append("    classDef safety fill:#fee2e2,stroke:#b91c1c,color:#280707;")
    return "\n".join(lines) + "\n"


def _ident(node_id: str) -> str:
    return "n_" + "".join(char if char.isalnum() else "_" for char in node_id)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "graph")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    graph = load_graph()
    outputs: dict[Path, str] = {
        args.out / "model.json": json.dumps(graph.to_dict(), indent=2) + "\n"
    }
    for capability in graph.by_type("Capability"):
        name = capability.id.split(":", 1)[1]
        outputs[args.out / f"{name}.mmd"] = mermaid(graph, capability.id)

    stale = [
        path for path, content in outputs.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]

    if args.check:
        if stale:
            for path in stale:
                print(f"ERROR: {path.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        print(f"graph exports up to date ({len(outputs)} files)")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print(f"wrote {len(outputs)} file(s) to {args.out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
